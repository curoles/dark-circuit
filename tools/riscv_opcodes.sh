#!/bin/bash
# Generate from riscv-opcodes, the official machine-readable opcodes (BSD-3-Clause license):
# - rtl/lib/riscv/riscv_instr_pkg.sv: instruction encodings, package RiscvInstrPkg;
# - rtl/lib/riscv/riscv_csr_pkg.sv: CSR addresses, package RiscvCsrPkg.
#
# Usage: tools/riscv_opcodes.sh [extension ...]    default: rv_i rv32_i rv_zicsr rv_system
#
# Clones riscv-opcodes at COMMIT into a temporary directory, runs its generator
# for SystemVerilog and splits its output into the two packages. Encodings are of the
# given extensions; CSR addresses are all that riscv-opcodes knows.
# Needs git and python3. Run it again only to add extensions (M, ...) or to move to a
# newer COMMIT.
set -euo pipefail

REPO=https://github.com/riscv/riscv-opcodes.git
COMMIT=f24ac23ec9fa947011781a09cd6fd25a7c36dc45
ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT=$ROOT/rtl/lib/riscv/riscv_instr_pkg.sv
OUT_CSR=$ROOT/rtl/lib/riscv/riscv_csr_pkg.sv

if [ $# -gt 0 ]; then EXTENSIONS=("$@"); else EXTENSIONS=(rv_i rv32_i rv_zicsr rv_system); fi

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

git clone --quiet "$REPO" "$TMP/riscv-opcodes"
git -C "$TMP/riscv-opcodes" checkout --quiet "$COMMIT"
# The generator writes inst.sverilog into the current directory.
(cd "$TMP" && PYTHONPATH="$TMP/riscv-opcodes/src" python3 -m riscv_opcodes -sverilog "${EXTENSIONS[@]}" > /dev/null)

mkdir -p "$(dirname "$OUT")"
{
    echo "// THIS FILE IS GENERATED, DO NOT EDIT MANUALLY!"
    echo "// Generated by tools/riscv_opcodes.sh from riscv-opcodes, extensions: ${EXTENSIONS[*]},"
    echo "// $REPO commit $COMMIT."
    echo "//"
    echo "// RISC-V instruction encodings: ? marks bits of operands, match them with casez."
    echo "//"
    echo "// License of riscv-opcodes:"
    sed -e 's|^|// |' -e 's| *$||' "$TMP/riscv-opcodes/LICENSE"
    echo ""
    echo "package RiscvInstrPkg;"
    echo ""
    echo "    // A decoder uses some of the encodings, not all."
    echo "    /* verilator lint_off UNUSEDPARAM */"
    grep -E '^ *localparam \[31:0\] ' "$TMP/inst.sverilog" | sed 's/^ */    /'
    echo "    /* verilator lint_on UNUSEDPARAM */"
    echo ""
    echo "endpackage"
} > "$OUT"

{
    echo "// THIS FILE IS GENERATED, DO NOT EDIT MANUALLY!"
    echo "// Generated by tools/riscv_opcodes.sh from riscv-opcodes,"
    echo "// $REPO commit $COMMIT."
    echo "//"
    echo "// RISC-V CSR addresses: CSR_<name> is the 12-bit address of CSR <name>."
    echo "//"
    echo "// License of riscv-opcodes:"
    sed -e 's|^|// |' -e 's| *$||' "$TMP/riscv-opcodes/LICENSE"
    echo ""
    echo "package RiscvCsrPkg;"
    echo ""
    echo "    // A design has some of the CSRs, not all."
    echo "    /* verilator lint_off UNUSEDPARAM */"
    grep -E '^ *localparam logic \[11:0\] CSR_' "$TMP/inst.sverilog" | sed 's/^ */    /'
    echo "    /* verilator lint_on UNUSEDPARAM */"
    echo ""
    echo "endpackage"
} > "$OUT_CSR"

echo "riscv_opcodes: wrote ${OUT#"$ROOT"/} ($(grep -c 'localparam' "$OUT") encodings)"
echo "riscv_opcodes: wrote ${OUT_CSR#"$ROOT"/} ($(grep -c 'localparam' "$OUT_CSR") CSR addresses)"
